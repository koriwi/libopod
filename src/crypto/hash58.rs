/// Fixed 18-byte seed for key derivation.
const FIXED: [u8; 18] = [
    0x67, 0x23, 0xFE, 0x30, 0x45, 0x33, 0xF8, 0x90, 0x99, 0x21, 0x07, 0xC1, 0xD0, 0x12, 0xB2, 0xA1,
    0x07, 0x81,
];

/// mhbd offsets used by the signature computation.
const OFFSET_DB_ID: usize = 0x18;
const OFFSET_UNK32: usize = 0x32;
const OFFSET_HASHING_SCHEME: usize = 0x30;
const OFFSET_HASH58: usize = 0x58;
const HASH58_SCHEME: u16 = 1;

/// The 64-byte HMAC key derived from an 8-byte `FireWire` GUID.
fn derive_key(firewire_id: &[u8]) -> [u8; 64] {
    let mut y = [0u8; 16];
    for (i, pair) in firewire_id.chunks_exact(2).take(4).enumerate() {
        let (a, b) = (pair[0], pair[1]);
        let lcm = lcm(u32::from(a), u32::from(b));
        let hi = ((lcm >> 8) & 0xFF) as usize;
        let lo = (lcm & 0xFF) as usize;
        y[i * 4] = TABLE1[hi];
        y[i * 4 + 1] = TABLE2[hi];
        y[i * 4 + 2] = TABLE1[lo];
        y[i * 4 + 3] = TABLE2[lo];
    }
    let digest: [u8; 20] = {
        let mut hasher = sha1::Sha1::new();
        hasher.update(FIXED);
        hasher.update(y);
        hasher.finalize().into()
    };
    let mut key = [0u8; 64];
    key[..20].copy_from_slice(&digest);
    key
}

fn lcm(a: u32, b: u32) -> u32 {
    if a == 0 || b == 0 {
        return 1;
    }
    (a * b) / gcd(a, b)
}

fn gcd(mut a: u32, mut b: u32) -> u32 {
    while b != 0 {
        let remainder = a % b;
        a = b;
        b = remainder;
    }
    a
}

/// HMAC-SHA1 with a 64-byte key (the HASH58 construction).
fn hmac_sha1(key: &[u8; 64], message: &[u8]) -> [u8; 20] {
    let mut inner = [0u8; 64];
    let mut outer = [0u8; 64];
    for (index, byte) in key.iter().enumerate() {
        inner[index] = byte ^ 0x36;
        outer[index] = byte ^ 0x5C;
    }
    let mut inner_hasher = sha1::Sha1::new();
    inner_hasher.update(inner);
    inner_hasher.update(message);
    let inner_digest = inner_hasher.finalize();
    let mut outer_hasher = sha1::Sha1::new();
    outer_hasher.update(outer);
    outer_hasher.update(inner_digest);
    outer_hasher.finalize().into()
}

/// Returns the HASH58 digest over an `iTunesDB` whose `db_id`, `unk_0x32`,
/// and `hash58` fields are already zeroed and whose hashing scheme is `1`.
#[must_use]
pub fn calculate(firewire_id: &[u8], itunesdb: &[u8]) -> [u8; 20] {
    let key = derive_key(firewire_id);
    hmac_sha1(&key, itunesdb)
}

/// Signs an uncompressed classic `iTunesDB` in place: zeroes the covered
/// fields, sets the hashing scheme, computes the HMAC-SHA1 digest, writes it
/// at `0x58`, and restores the `db_id` / `unk_0x32` fields.
pub fn sign_database(firewire_id: &[u8], itunesdb: &mut [u8]) {
    debug_assert_eq!(&itunesdb[..4], b"mhbd");
    debug_assert!(itunesdb.len() >= OFFSET_HASH58 + 20);
    let backup_db_id = itunesdb[OFFSET_DB_ID..OFFSET_DB_ID + 8].to_vec();
    let backup_unk32 = itunesdb[OFFSET_UNK32..OFFSET_UNK32 + 20].to_vec();
    itunesdb[OFFSET_DB_ID..OFFSET_DB_ID + 8].fill(0);
    itunesdb[OFFSET_UNK32..OFFSET_UNK32 + 20].fill(0);
    itunesdb[OFFSET_HASH58..OFFSET_HASH58 + 20].fill(0);
    itunesdb[OFFSET_HASHING_SCHEME..OFFSET_HASHING_SCHEME + 2]
        .copy_from_slice(&HASH58_SCHEME.to_le_bytes());
    let digest = calculate(firewire_id, itunesdb);
    itunesdb[OFFSET_HASH58..OFFSET_HASH58 + 20].copy_from_slice(&digest);
    itunesdb[OFFSET_DB_ID..OFFSET_DB_ID + 8].copy_from_slice(&backup_db_id);
    itunesdb[OFFSET_UNK32..OFFSET_UNK32 + 20].copy_from_slice(&backup_unk32);
}

/// Verifies the stored HASH58 signature of a classic `iTunesDB`.
#[must_use]
pub fn verify(firewire_id: &[u8], itunesdb: &[u8]) -> bool {
    if itunesdb.len() < OFFSET_HASH58 + 20 {
        return false;
    }
    let mut copy = itunesdb.to_vec();
    sign_database(firewire_id, &mut copy);
    copy[OFFSET_HASH58..OFFSET_HASH58 + 20] == itunesdb[OFFSET_HASH58..OFFSET_HASH58 + 20]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lcm_and_gcd_are_consistent() {
        assert_eq!(gcd(12, 8), 4);
        assert_eq!(lcm(12, 8), 24);
        assert_eq!(lcm(0, 7), 1);
    }

    #[test]
    fn key_derivation_uses_fixed_seed_and_sboxes() {
        // Deterministic: the same GUID always yields the same 64-byte key.
        let guid = [0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77];
        let key = derive_key(&guid);
        assert_eq!(key.len(), 64);
        assert_ne!(key, [0u8; 64]);
        assert_eq!(key, derive_key(&guid));
        // The key only depends on the first eight GUID bytes.
        assert_eq!(
            derive_key(&guid),
            derive_key(&[0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x99])
        );
    }

    #[test]
    fn sign_then_verify_round_trips() {
        let mut itunesdb = vec![0u8; 1024];
        itunesdb[..4].copy_from_slice(b"mhbd");
        itunesdb[OFFSET_DB_ID..OFFSET_DB_ID + 8]
            .copy_from_slice(&0x1234_5678_9abc_def0u64.to_le_bytes());
        itunesdb[OFFSET_UNK32..OFFSET_UNK32 + 20].fill(0xAB);
        let guid = [0xDE, 0xAD, 0xBE, 0xEF, 0x01, 0x23, 0x45, 0x67];
        sign_database(&guid, &mut itunesdb);
        assert!(verify(&guid, &itunesdb));
        // A different GUID must not verify.
        let other = [0xFF; 8];
        assert!(!verify(&other, &itunesdb));
        // Tampering with the payload must not verify.
        let mut tampered = itunesdb.clone();
        tampered[100] ^= 0x01;
        assert!(!verify(&guid, &tampered));
    }

    #[test]
    fn verifies_the_attached_nano3_signature() {
        // Real-device vector: the Nano 3G's own iTunesDB must verify against
        // the FireWire GUID stored in its SysInfoExtended.
        let base = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("files_nano3");
        let itunesdb = base.join("iTunes/iTunesDB");
        if !itunesdb.is_file() {
            return;
        }
        let extended = std::fs::read(base.join("Device/SysInfoExtended")).unwrap();
        let value = plist::Value::from_reader_xml(std::io::Cursor::new(&extended)).unwrap();
        let guid_text = value
            .as_dictionary()
            .and_then(|dict| dict.get("FireWireGUID"))
            .and_then(plist::Value::as_string)
            .unwrap();
        let mut guid = [0u8; 8];
        for (index, byte) in guid.iter_mut().enumerate() {
            *byte = u8::from_str_radix(&guid_text[index * 2..index * 2 + 2], 16).unwrap();
        }
        let database = std::fs::read(&itunesdb).unwrap();
        assert!(
            verify(&guid, &database),
            "the stored Nano 3G HASH58 signature does not verify"
        );
    }
}
