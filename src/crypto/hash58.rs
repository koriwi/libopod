//! HASH58 — the iTunesDB signature for iPod Classic, Nano 3G, and Nano 4G.
//!
//! HASH58 is an HMAC-SHA1 over the whole (uncompressed) `iTunesDB` file,
//! keyed from the device.s 8-byte `FireWire` GUID. The signature is stored at
//! mhbd offset `0x58` and covers the file with the `db_id` (0x18), the
//! `unk_0x32` region (0x32), and the signature field itself zeroed, with the
//! hashing scheme field (0x30) set to `1`.
//!
//! The key derivation maps each pair of `FireWire` bytes through the AES
//! S-box / inverse S-box via the LCM of the pair, SHA-1s the result with a
//! fixed 18-byte seed, and pads the 20-byte digest to a 64-byte HMAC key.
//!
//! This is a clean-room-style Rust implementation of the published algorithm
//! (reference: libgpod's `itdb_hash58.c` as documented by iOpenPod).

